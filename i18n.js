  /* ─── Current language ─── */
  var lang = localStorage.getItem('yappi_lang') || 'ru';

  /* ─── Apply translations to DOM ─── */
  function applyLang(newLang) {
    lang = newLang;
    localStorage.setItem('yappi_lang', lang);
    /* do NOT change document.documentElement.lang — triggers browser auto-translate */

    var t = TRANS[lang] || TRANS['ru'];

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (t[key] !== undefined) el.textContent = t[key];
    });

    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-html');
      if (t[key] !== undefined) el.innerHTML = t[key];
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-placeholder');
      if (t[key] !== undefined) el.placeholder = t[key];
    });

    /* update lang switcher buttons */
    document.querySelectorAll('.lang-switch').forEach(function (btn) {
      btn.textContent = lang === 'ru' ? 'EN' : 'RU';
      btn.setAttribute('title', lang === 'ru' ? 'Switch to English' : 'Переключить на русский');
    });

    /* special: rating votes text (if exists and shows "loading") */
    var rv = document.getElementById('ratingVotes');
    if (rv && (rv.textContent === 'загрузка...' || rv.textContent === 'loading...')) {
      rv.textContent = t['rating.loading'];
    }
  }

  /* ─── Global toggle ─── */
  window.t = function (key) { return (TRANS[lang] || TRANS.ru)[key] || key; };
  window.switchLang = function () {
    applyLang(lang === 'ru' ? 'en' : 'ru');
  };

  /* ─── On DOMContentLoaded ─── */
  document.addEventListener('DOMContentLoaded', function () {
    /* always call applyLang to set button text correctly */
    applyLang(lang);
  });
